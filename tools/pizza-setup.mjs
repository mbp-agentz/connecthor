// Finds the pizza places near the Pentagon on BestTime.app and writes pizza-venues.json: venue ids,
// names, positions and each weekday's typical hourly busyness in US Eastern clock hours.
// Run by .github/workflows/pizza-venues.yml with the BESTTIME_PRIVATE_KEY secret (monthly, or by hand).
// Cost per run: 1 search credit + 2 per forecast venue (max 20); the week queries right after are free.
import { writeFileSync } from 'node:fs';

const KEY = process.env.BESTTIME_PRIVATE_KEY;
if (!KEY) { console.error('BESTTIME_PRIVATE_KEY is not set'); process.exit(1); }
const API = 'https://besttime.app/api/v1';
const PENTAGON = { lat: 38.8719, lng: -77.0563 };
const RADIUS_M = 2500, MAX_VENUES = 8;
const OUT = new URL('../pizza-venues.json', import.meta.url);

async function call(path, params, method = 'GET') {
  const url = new URL(API + path);
  for (const [k, v] of Object.entries(params)) url.searchParams.set(k, String(v));
  const res = await fetch(url, { method, signal: AbortSignal.timeout(30000) });
  const data = await res.json().catch(() => ({}));
  if (!res.ok || /^error$/i.test(data.status || '')) throw new Error(`${path}: HTTP ${res.status} ${data.message || ''}`.trim());
  return data;
}
const sleep = ms => new Promise(r => setTimeout(r, ms));

const miles = (a, b) => {
  const R = 3958.8, rad = Math.PI / 180, dLat = (b.lat - a.lat) * rad, dLng = (b.lng - a.lng) * rad;
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(a.lat * rad) * Math.cos(b.lat * rad) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
};
// BestTime addresses vary ("…Arlington, VA 22202 United States", "…Arlington VA 22202"), so name the
// neighbourhood from the ZIP code; 22202 spans Pentagon City (north) and Crystal City (south)
const ZIP_AREA = { 22201: 'Clarendon', 22203: 'Ballston', 22204: 'Columbia Pike', 22206: 'Shirlington', 22209: 'Rosslyn', 20001: 'Washington DC', 20024: 'Washington DC' };
const areaOf = (addr, lat) => {
  const zip = (String(addr || '').match(/\b(2\d{4})\b/) || [])[1];
  if (zip === '22202') return lat >= 38.858 ? 'Pentagon City' : 'Crystal City';
  return ZIP_AREA[zip] || 'Arlington';
};

// BestTime days run 6 AM to 5 AM (day_raw[0] = 6:00, day 0 = Monday). The page wants clock hours,
// so 00:00-05:00 of a weekday come from the end of the previous BestTime day.
function clockWeek(weekRaw) {
  const byDay = Array.from({ length: 7 }, (_, d) => (weekRaw.find(x => x.day_int === d) || {}).day_raw || Array(24).fill(0));
  return byDay.map((_, d) => Array.from({ length: 24 }, (_, h) => h >= 6 ? byDay[d][h - 6] : byDay[(d + 6) % 7][h + 18]));
}

const { api_key_public: PUB } = await call('/keys/' + KEY, {});
if (!PUB) throw new Error('could not read the public key for this private key');

console.log(`Searching BestTime for pizza within ${RADIUS_M} m of the Pentagon…`);
const job = await call('/venues/search', { api_key_private: KEY, q: 'pizza', num: 20, lat: PENTAGON.lat, lng: PENTAGON.lng, radius: RADIUS_M, format: 'raw' }, 'POST');
let progress;
for (let i = 0; i < 72; i++) {
  await sleep(5000);
  progress = await call('/venues/progress', { job_id: job.job_id, collection_id: job.collection_id, format: 'raw' });
  if (progress.job_finished) break;
}
if (!progress?.job_finished) throw new Error('venue search did not finish within 6 minutes');

const found = (progress.venues || [])
  .filter(v => v.venue_id && v.forecast)
  .map(v => ({ ...v, lat: +v.venue_lat, lng: +(v.venue_lng ?? v.venue_lon) }))
  .filter(v => isFinite(v.lat) && isFinite(v.lng))
  .map(v => ({ ...v, dist: miles(PENTAGON, v) }))
  .sort((a, b) => a.dist - b.dist)
  .slice(0, MAX_VENUES);
console.log(`${progress.venues?.length || 0} venues found, ${found.length} with a forecast kept.`);

const venues = [];
for (const v of found) {
  try {
    const w = await call('/forecasts/week/raw2', { venue_id: v.venue_id, api_key_public: PUB });
    venues.push({ venue_id: v.venue_id, name: v.venue_name, address: v.venue_address, area: areaOf(v.venue_address, v.lat), lat: +v.lat.toFixed(5), lng: +v.lng.toFixed(5), dist: Math.round(v.dist * 10) / 10, week: clockWeek(w.analysis?.week_raw || []) });
  } catch (e) { console.log(`  skipped ${v.venue_name}: ${e.message}`); }
}
if (!venues.length) throw new Error('no venue had usable forecast data; pizza-venues.json left unchanged');

writeFileSync(OUT, JSON.stringify({ updated: new Date().toISOString(), source: 'BestTime.app', note: 'Generated by tools/pizza-setup.mjs. Do not edit by hand.', venues }, null, 1) + '\n');
console.log('\nWrote pizza-venues.json:');
for (const v of venues) console.log(`  ${v.dist.toFixed(1)} mi  ${v.name}  (${v.address})`);
